def connection_text(c):
    lines = [f"IED Inspector {__version__} – MMS connection report", "=" * 60,
             f"Target      : {c['ip']}:{c.get('port')}", f"Started     : {ts(c.get('started'))}",
             f"Duration    : {c.get('duration_ms')} ms", f"Backend     : {c.get('backend')}",
             f"Result      : {'CONNECTED' if c.get('ok') else 'FAILED – ' + str(c.get('error'))}"]
    idt = c.get("identity") or {}
    lines += [f"Identity    : {idt.get('vendor', '')} {idt.get('model', '')} {idt.get('revision', '')}",
              f"LDs         : {', '.join(c.get('domains', []))}", ""]
    for g in c.get("gocbs", []) + c.get("svcbs", []):
        lines.append(f"[{g['kind']}] {g['ref']}")
        if g.get("error"):
            lines.append(f"   ERROR {g['error']}")
            continue
        vid = g.get("vlanId")
        lines.append(f"   VLAN {vid}{' (0x%03X)' % vid if isinstance(vid, int) else ''}  prio {g.get('vlanPriority')}  "
                     f"APPID {_hexapp(g.get('appId'))}  MAC {g.get('mac')}  enabled {g.get('enabled')}  confRev {g.get('confRev')}")
        lines.append(f"   ID {g.get('id')}  DataSet {g.get('datSet')}")
        for m in g.get("members", []):
            lines.append(f"     [{m['index']}] {m['ref']} = {m['text']}")
    if c.get("supervision"):
        lines += ["", "Subscription supervision (LGOS/LSVS):"]
        for x in c["supervision"]:
            st = {True: "RECEIVING", False: "NOT RECEIVING", None: "unknown"}[x.get("st")]
            lines.append(f"  {x['ld']}/{x['ln']:<8} {st:<14} {x.get('ref')}  lastStNum {x.get('lastStNum')}  "
                         f"confRev {x.get('confRevNum')}/{x.get('rxConfRevNum')}")
    for v in c.get("vendorSupervision", []):
        st = {True: "OK", False: "PROBLEM", None: "?"}[v.get("ok")]
        lines += ["", f"Vendor supervision {v['ld']}/{v['ln']} ({v['profile']}): {st} – {v['summary']}"]
        lines += [f"    {k} = {x}" for k, x in v["values"].items()]
    lines += ["", "Log:"] + ["  " + x for x in c.get("log", [])]
    return "\n".join(lines) + "\n"


def summary_html(session, a, scd_name):
    up = time.time() - session["started"]
    b = [f"<h1>Session summary</h1><div class='meta'>Session started {ts(session['started'])} · running "
         f"{int(up // 3600)} h {int(up % 3600 // 60)} min · SCD {e(scd_name or 'not loaded')}</div>"]
    conns = session["connections"]
    ok = sum(1 for c in conns if c.get("ok"))
    b.append(f"<h2>MMS connections ({len(conns)}, {ok} successful)</h2><table><tr><th>#</th><th>Time</th><th>Target</th>"
             "<th>Result</th><th>Identity</th><th>GOOSE CBs</th><th>SV CBs</th><th>VLANs (MMS)</th><th>Duration</th></tr>")
    for c in conns:
        idt = c.get("identity") or {}
        vl = sorted({g.get("vlanId") for g in c.get("gocbs", []) + c.get("svcbs", []) if g.get("vlanId") is not None})
        b.append(f"<tr><td>{c['id']}</td><td>{ts(c.get('started'))}</td><td>{e(c['ip'])}:{e(c.get('port'))}</td>"
                 f"<td>{badge('ok') if c.get('ok') else badge('error') + ' ' + e(c.get('error'))}</td>"
                 f"<td>{e(idt.get('vendor'))} {e(idt.get('model'))}</td><td>{len(c.get('gocbs', []))}</td>"
                 f"<td>{len(c.get('svcbs', []))}</td><td>{e(', '.join(map(str, vl)))}</td><td>{e(c.get('duration_ms'))} ms</td></tr>")
    b.append("</table>")
    b.append("<h2>Captures and pcap files</h2><table><tr><th>Source</th><th>Frames</th><th>GOOSE streams</th>"
             "<th>SV streams</th><th>From</th><th>To</th><th>Problems</th></tr>")
    for snap in session["capture_snapshots"]:
        bad = [g for g in snap["goose"] + snap["sv"] if g["status"] != "ok" or g.get("warnings")]
        b.append(f"<tr><td>{e(snap['source'])}</td><td>{snap['frames']}</td><td>{len(snap['goose'])}</td><td>{len(snap['sv'])}</td>"
                 f"<td>{ts(snap['first'])}</td><td>{ts(snap['last'])}</td>"
                 f"<td>{'<br>'.join(e((g.get('gocbRef') or g.get('svID')) + ': ' + ', '.join(([g['status']] if g['status'] != 'ok' else []) + g.get('warnings', []))) for g in bad[:12])}</td></tr>")
    b.append("</table>")
    if session.get("scd_history"):
        b.append("<h2>SCD files loaded</h2><table><tr><th>Time</th><th>File</th><th>IEDs</th><th>Errors</th><th>Warnings</th></tr>")
        for h in session["scd_history"]:
            b.append(f"<tr><td>{ts(h['ts'])}</td><td>{e(h['file'])}</td><td>{h['ieds']}</td><td>{h['errors']}</td><td>{h['warnings']}</td></tr>")
        b.append("</table>")
    if session.get("sim_history"):
        b.append("<h2>Simulator activity</h2><table><tr><th>Time</th><th>Action</th></tr>")
        for h in session["sim_history"]:
            b.append(f"<tr><td>{ts(h['ts'])}</td><td>{e(h['text'])}</td></tr>")
        b.append("</table>")
    c = a["counts"]
    b.append("<h2>Current comparison result</h2><div class='counts'>" +
             "".join(f"<span>{badge(k)} {c.get(k, 0)}</span>" for k in ("error", "warning", "info")) + "</div>")
    b.append("<table><tr><th>Device</th><th>Reachable</th><th>Status</th><th>VLANs required</th><th>Notes</th></tr>")
    for d in a["devices"]:
        b.append(f"<tr><td>{e(d['name'])}</td><td>{ {True: 'yes', False: 'NO', None: '–'}[d.get('reachable')] }</td>"
                 f"<td>{badge(d['status'])}</td><td>{e(', '.join(map(str, d['requiredVlans'])))}</td>"
                 f"<td>{'<br>'.join(e(x) for x in d['findings'][:4])}</td></tr>")
    b.append("</table>")
    b.append("<h2>Activity log</h2><table><tr><th>Time</th><th>Event</th></tr>")
    for ev in session["log"][-500:]:
        b.append(f"<tr><td>{ts(ev['ts'])}</td><td>{e(ev['text'])}</td></tr>")
    b.append("</table>")
    return page("Session summary", "".join(b))


def to_json(obj):
    def default(o):
        if isinstance(o, set):
            return sorted(o, key=str)
        if isinstance(o, bytes):
            return o.hex()
        if hasattr(o, "to_json"):
            return o.to_json()
        return str(o)
    return json.dumps(obj, indent=2, default=default)
