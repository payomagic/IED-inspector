def comparison_csv(a, table="controlblocks"):
    out = io.StringIO()
    w = csv.writer(out, delimiter=";")
    if table == "signals":
        w.writerow(["device", "ip", "control_block", "index", "signal", "vlan", "scd_ref", "mms_ref", "mms_value",
                    "network_value", "subscribers", "status", "note"])
        for s in a["signals"]:
            w.writerow([s["device"], s["ip"], s["cb"], s["index"], s["ref"], s["vlanId"], s["scdRef"], s["mmsRef"],
                        s["mmsValue"], s["wireValue"], ",".join(s["subscribers"]), s["status"], s["note"]])
    elif table == "findings":
        w.writerow(["severity", "category", "device", "object", "message"])
        for f in a["findings"]:
            w.writerow([f["severity"], f["category"], f["device"], f["object"], f["message"]])
    else:
        hdr = ["device", "ip", "read_from", "kind", "control_block", "status"]
        for fld in ("vlanId", "vlanPriority", "appId", "mac", "confRev", "id", "datSet"):
            hdr += [f"{fld}_scd", f"{fld}_mms", f"{fld}_network", f"{fld}_result"]
        hdr += ["network_status", "subscribers", "subscribers_receiving", "findings"]
        w.writerow(hdr)
        for r in a["controlBlocks"]:
            row = [r["device"], r["ip"], r.get("readFrom"), r["kind"], r["ref"], r["status"]]
            for ch in r["checks"]:
                v = ch["values"]
                row += [v.get("scd"), v.get("mms"), v.get("wire"), ch["status"]]
            rx = r.get("supervision") or []
            row += [(r.get("wire") or {}).get("status"), ",".join(sorted({s["device"] for s in r["subscribers"]})),
                    ",".join(f"{x['device']}:{'yes' if x.get('st') else 'NO'}" for x in rx),
                    " | ".join(m for _, m in r["findings"])]
            w.writerow(row)
    return "\ufeff" + out.getvalue()


